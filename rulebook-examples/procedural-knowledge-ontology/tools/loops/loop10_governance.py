"""Loop 10 (theme E): governance of the model itself, and of the procedures it holds.

The ontology governance essay says a deployed model drifts from the organization it
describes from the day it passes its tests, and that only named ownership, semantic
versioning, a change process tied to competency questions, and periodic review of those
questions keep it honest. Loops 1-9 witnessed procedures; almost nothing witnessed the
model's own governance. This rulebook is its own ontology (its schema lives in
RulebookFields/RulebookTables, its competency questions in RoleQuestions, its releases in
RulebookReleases), so governance of "the model" is governance of this rulebook, and
governance of a procedure family is governance of its ProcedureVersions.

Every predicate is asked for by the steward, the authority, a release manager or a
safety officer doing that governance work, and each seeded breach is kept as evidence.
"""
