#!/usr/bin/env python3
"""
side_by_side.py - the banking rules computed twice, by Postgres and by COBOL,
from the same rulebook and the same data, compared cell by cell.

    ./side-by-side.sh        (or: python3 side_by_side.py [--now ISO])

  Postgres  postgres-bootstrap/ (generated by rulebook-to-postgres) applied to a
            throwaway database on your LOCAL Postgres (PGHOST/PGPORT/PGUSER,
            default localhost:5432, user postgres), every vw_* view read, the
            database dropped again
  COBOL     cobol/src/ (generated by rulebook-to-cobol) compiled with GnuCOBOL
            and run by erb_cobol.py on the rulebook's raw facts

Every computed column of every row is compared; numbers numerically, NULL and
"" as the same blank. Writes cobol/side-by-side.html and exits non-zero if any
cell differs. Needs python3, GnuCOBOL (cobc) and Postgres client tools.
"""

import argparse
import html
import json
import os
import subprocess
import sys
import time
from pathlib import Path

from erb_cobol import CobolError, HERE, run

PROJECT = HERE.parent
SQL_ORDER = ['00-bootstrap.sql', '01-drop-and-create-tables.sql', '01b-customize-schema.sql',
             '02-create-functions.sql', '02b-customize-functions.sql', '03-create-views.sql',
             '03b-customize-views.sql', '04-create-policies.sql', '04b-customize-policies.sql',
             '05-insert-data.sql', '05b-customize-data.sql']
PG = ['-h', os.environ.get('PGHOST', 'localhost'), '-p', os.environ.get('PGPORT', '5432'),
      '-U', os.environ.get('PGUSER', 'postgres')]


def psql(db, *args):
    env = dict(os.environ, PGTZ='UTC')
    return subprocess.run(['psql', *PG, '-d', db, '-v', 'ON_ERROR_STOP=1', '-q', *args],
                          check=True, capture_output=True, text=True, env=env).stdout


def postgres_rows():
    db = f'erb_side_by_side_{os.getpid()}'
    subprocess.run(['createdb', *PG, db], check=True)
    started = time.time()
    try:
        for name in SQL_ORDER:
            path = PROJECT / 'postgres-bootstrap' / name
            if path.exists():
                psql(db, '-f', str(path))
        views = psql(db, '-At', '-c', "SELECT viewname FROM pg_views WHERE schemaname = 'public' "
                                      "AND viewname LIKE 'vw\\_%' ORDER BY 1").split()
        tables = {v[3:]: json.loads(psql(db, '-At', '-c', f"SELECT COALESCE(json_agg(v), '[]') FROM {v} v"))
                  for v in views}
    finally:
        subprocess.run(['dropdb', *PG, db], check=False)
    return tables, round(time.time() - started, 2)


def flat(name):
    return name.replace('_', '').lower()


def same(a, b):
    if a in (None, '') and b in (None, ''):
        return True
    if isinstance(a, bool) or isinstance(b, bool):
        return a is b
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return abs(a - b) < 1e-9
    if isinstance(a, (int, float)) or isinstance(b, (int, float)):
        try:
            return abs(float(a) - float(b)) < 1e-9
        except (TypeError, ValueError):
            return False
    return a == b


def cell(v):
    return '<span class="blank">NULL</span>' if v is None else html.escape(json.dumps(v, ensure_ascii=False) if not isinstance(v, str) else v)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--rulebook', default=str(PROJECT / 'effortless-rulebook' / 'effortless-banking-rulebook.json'))
    parser.add_argument('--now', default='')
    args = parser.parse_args()
    rulebook = json.loads(Path(args.rulebook).read_text(encoding='utf-8'))
    try:
        cobol, info = run(rulebook, args.now)
    except CobolError as exc:
        print(f"side-by-side: {exc}", file=sys.stderr)
        sys.exit(1)
    manifest = json.loads((HERE / 'src' / 'erb_manifest.json').read_text(encoding='utf-8'))
    postgres, pg_seconds = postgres_rows()
    pg_by_flat = {flat(k): v for k, v in postgres.items()}

    total = differ = 0
    sections = []
    for table in manifest['tables']:
        if table['name'] == '__meta__':
            continue
        computed = [f for f in table['fields'] if f['type'] not in ('raw', 'relationship')]
        theirs = {r.get('name'): {flat(k): v for k, v in r.items()} for r in pg_by_flat.get(flat(table['snake']), [])}
        lines, bad = [], 0
        for row in cobol[table['snake']]:
            other = theirs.get(row.get('name'), {})
            for f in computed:
                ours, pg = row.get(f['snake']), other.get(flat(f['snake']))
                ok = same(ours, pg)
                total += 1
                bad += 0 if ok else 1
                lines.append(f"<tr class=\"{'ok' if ok else 'bad'}\"><td>{html.escape(str(row.get('name')))}</td>"
                             f"<td>{html.escape(f['name'])}</td><td>{cell(ours)}</td><td>{cell(pg)}</td>"
                             f"<td>{'✓' if ok else '✗ different'}</td></tr>")
        differ += bad
        sections.append(f"<details{' open' if bad else ''}><summary><b>{html.escape(table['name'])}</b> — "
                        f"{len(cobol[table['snake']])} rows × {len(computed)} computed fields, "
                        f"{'all identical' if not bad else f'{bad} different'}</summary>"
                        f"<table><tr><th>Row (Name)</th><th>Field</th><th>COBOL</th><th>Postgres</th><th></th></tr>"
                        + ''.join(lines) + "</table></details>")
    verdict = (f"All {total} computed cells are identical." if not differ
               else f"{differ} of {total} computed cells differ.")
    page = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1"><title>Banking: COBOL vs Postgres</title>
<style>
:root {{ --bg:#fff; --fg:#1d1d1f; --muted:#6e6e73; --line:#e5e5ea; --ok:#1a7f37; --bad:#c62828; }}
@media (prefers-color-scheme: dark) {{ :root {{ --bg:#111; --fg:#f2f2f7; --muted:#a1a1a6; --line:#2c2c2e; --ok:#3fb950; --bad:#ff6b6b; }} }}
body {{ background:var(--bg); color:var(--fg); font:15px/1.5 system-ui, sans-serif; margin:0 auto; max-width:1100px; padding:24px 16px; }}
h1 {{ font-size:22px; margin:0 0 4px; }} .muted {{ color:var(--muted); }}
.verdict {{ font-size:18px; margin:16px 0; color:{'var(--ok)' if not differ else 'var(--bad)'}; }}
table {{ border-collapse:collapse; width:100%; margin:8px 0 16px; font-size:13px; }}
td, th {{ border-bottom:1px solid var(--line); padding:4px 8px; text-align:left; vertical-align:top; overflow-wrap:anywhere; }}
tr.bad td {{ color:var(--bad); }} tr.ok td:last-child {{ color:var(--ok); }} .blank {{ color:var(--muted); }}
details {{ border:1px solid var(--line); border-radius:8px; padding:8px 12px; margin:8px 0; }} summary {{ cursor:pointer; }}
</style></head><body>
<h1>Effortless Banking: the same rules in COBOL and in Postgres</h1>
<p class="muted">One rulebook (effortless-rulebook/effortless-banking-rulebook.json), two generated substrates,
the same data. COBOL: rulebook-to-cobol's ERBRULES/ERBBATCH compiled with GnuCOBOL (compile {info['compile']}s,
run {info['run']}s; {html.escape(info['status'])}). Postgres: rulebook-to-postgres's SQL, views read in {pg_seconds}s.</p>
<p class="verdict">{verdict}</p>
{''.join(sections)}
</body></html>"""
    out = HERE / 'side-by-side.html'
    out.write_text(page, encoding='utf-8')
    print(f"side-by-side: {verdict} COBOL compile {info['compile']}s + run {info['run']}s; Postgres {pg_seconds}s.")
    print(f"side-by-side: wrote {out}")
    sys.exit(1 if differ else 0)


if __name__ == '__main__':
    main()
