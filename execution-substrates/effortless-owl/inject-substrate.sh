#!/bin/bash
set -e
set -o pipefail

# inject-substrate.sh for the effortless-owl execution substrate
#
# Regenerates the COMMERCIAL rulebook-to-owl output for the active domain with
# `effortless -buildLocal` from inside its output directory, then runs the test.
#
# Structure:
#   <domain>/effortless-owl/src/              - commercial transpiler output
#   execution-substrates/effortless-owl/      - this test runner

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

if [ -z "$ERB_DOMAIN_DIR" ] || [ ! -d "$ERB_DOMAIN_DIR" ]; then
    echo "FATAL: ERB_DOMAIN_DIR is not set or does not exist." >&2
    echo "  ERB_DOMAIN_DIR=${ERB_DOMAIN_DIR:-<unset>}" >&2
    exit 1
fi

OWL_OUT_DIR="$ERB_DOMAIN_DIR/effortless-owl"
GENERATED="$OWL_OUT_DIR/src/rules.shacl.ttl"

echo "=== Effortless-OWL Substrate: Regenerating from rulebook ==="
echo "  Output dir: $OWL_OUT_DIR"

mkdir -p "$OWL_OUT_DIR"
cd "$OWL_OUT_DIR"

BEFORE_MTIME=$(stat -f %m "$GENERATED" 2>/dev/null || echo 0)
effortless -buildLocal
AFTER_MTIME=$(stat -f %m "$GENERATED" 2>/dev/null || echo 0)

# -buildLocal can exit 0 having produced nothing (an unreachable transpiler).
# Grading the previous build's output would report a score for stale rules.
if [ "$AFTER_MTIME" = "0" ] || [ "$AFTER_MTIME" = "$BEFORE_MTIME" ]; then
    echo "FATAL: $GENERATED was not regenerated by this build." >&2
    echo "  rulebook-to-owl did not run; refusing to grade stale output." >&2
    exit 1
fi

cd "$SCRIPT_DIR"
"$SCRIPT_DIR/take-test.sh"
